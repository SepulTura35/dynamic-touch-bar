import AppKit
import Combine

nonisolated struct ClipboardItem: Equatable, Sendable {
    enum Kind: Equatable, Sendable {
        case text, url, email, number, image, files(Int), secret(Int), other
    }

    var kind: Kind
    var preview: String
    var characterCount: Int
    var date: Date

    var symbol: String {
        switch kind {
        case .text: "text.alignleft"
        case .url: "link"
        case .email: "envelope.fill"
        case .number: "number"
        case .image: "photo.fill"
        case .files: "doc.fill"
        case .secret: "lock.fill"
        case .other: "doc.on.clipboard"
        }
    }

    var title: String {
        switch kind {
        case .text: "Copied Text"
        case .url: "Copied Link"
        case .email: "Copied Email"
        case .number: "Copied Number"
        case .image: "Copied Image"
        case .files(let count): count == 1 ? "Copied File" : "Copied \(count) Files"
        case .secret: "Copied Sensitive Text"
        case .other: "Copied"
        }
    }
}

/// Privacy rules for the clipboard module — pure functions, unit-tested.
nonisolated enum ClipboardPrivacy {
    /// Pasteboard markers defined by nspasteboard.org and used by password managers.
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Apps whose copies are never previewed.
    static let ignoredBundleIDs: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop",
        "com.apple.keychainaccess", "com.apple.Passwords", "org.keepassxc.keepassxc", "com.lastpass.LastPass",
    ]

    static func isConcealed(types: [String]) -> Bool {
        types.contains { concealedTypes.contains($0) }
    }

    /// Heuristic for API keys, tokens and passwords: one "word", fairly long, high variety.
    static func looksLikeSecret(_ raw: String) -> Bool {
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        if text.hasPrefix("-----BEGIN") { return true }
        guard !text.contains(where: { $0.isWhitespace }) else { return false }
        guard (8...512).contains(text.count) else { return false }
        if isWebURL(text) || isEmail(text) { return false }
        let knownPrefixes = ["sk-", "sk_live_", "pk_live_", "ghp_", "gho_", "github_pat_", "xoxb-", "xoxp-", "AKIA", "AIza", "glpat-", "eyJ"]
        if text.count >= 16, knownPrefixes.contains(where: { text.hasPrefix($0) }) { return true }

        let hasLower = text.contains { $0.isLowercase }
        let hasUpper = text.contains { $0.isUppercase }
        let hasDigit = text.contains { $0.isNumber }
        let hasSymbol = text.contains { !$0.isLetter && !$0.isNumber }
        let classes = [hasLower, hasUpper, hasDigit, hasSymbol].filter { $0 }.count
        if classes >= 3 && text.count >= 10 { return true }
        if text.count >= 20 && classes >= 2 && entropyPerCharacter(text) > 3.5 { return true }
        return false
    }

    static func entropyPerCharacter(_ text: String) -> Double {
        guard !text.isEmpty else { return 0 }
        var counts: [Character: Int] = [:]
        for character in text { counts[character, default: 0] += 1 }
        let total = Double(text.count)
        return counts.values.reduce(0) { sum, count in
            let p = Double(count) / total
            return sum - p * log2(p)
        }
    }

    static func isWebURL(_ text: String) -> Bool {
        guard let url = URL(string: text), let scheme = url.scheme?.lowercased() else { return false }
        return (scheme == "http" || scheme == "https") && url.host != nil
    }

    static func isEmail(_ text: String) -> Bool {
        let parts = text.split(separator: "@")
        return parts.count == 2 && parts[1].contains(".") && !text.contains(where: { $0.isWhitespace })
    }

    static func classify(_ string: String, hideSecrets: Bool, previewLength: Int, now: Date) -> ClipboardItem {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        if hideSecrets && looksLikeSecret(trimmed) {
            return ClipboardItem(kind: .secret(trimmed.count), preview: "\(trimmed.count) characters hidden", characterCount: trimmed.count, date: now)
        }
        let kind: ClipboardItem.Kind
        if isWebURL(trimmed) { kind = .url }
        else if isEmail(trimmed) { kind = .email }
        else if Double(trimmed.replacingOccurrences(of: ",", with: "")) != nil { kind = .number }
        else { kind = .text }
        return ClipboardItem(kind: kind, preview: trimmed.truncatedForPreview(previewLength), characterCount: trimmed.count, date: now)
    }
}

/// Opt-in clipboard preview.
///
/// macOS offers no pasteboard-change notification, so while enabled this checks the
/// pasteboard's integer `changeCount` (no content is read) about once a second, with timer
/// tolerance so the system can coalesce wake-ups. Content is read only after a change, kept
/// in memory only, never written to disk or sent anywhere, and the full text is dropped after
/// one minute.
final class ClipboardMonitor: ObservableObject {
    @Published private(set) var latest: ClipboardItem?

    var hideSecrets = true
    var previewLength = 48
    var onCopy: ((ClipboardItem) -> Void)?

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount = 0
    private var fullText: String?
    private var expiryToken: ScheduledToken?
    private(set) var isRunning = false

    func setEnabled(_ enabled: Bool) {
        enabled ? start() : stop()
    }

    private func start() {
        guard !isRunning else { return }
        isRunning = true
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.9, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.4
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stop() {
        isRunning = false
        timer?.invalidate()
        timer = nil
        clear()
    }

    func clear() {
        latest = nil
        fullText = nil
        expiryToken?.cancel()
        expiryToken = nil
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if let frontmost = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           ClipboardPrivacy.ignoredBundleIDs.contains(frontmost) { return }
        let types = pasteboard.types?.map(\.rawValue) ?? []
        if ClipboardPrivacy.isConcealed(types: types) { return }

        let item: ClipboardItem
        let now = Date()
        if let files = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !files.isEmpty {
            item = ClipboardItem(kind: .files(files.count), preview: files.first?.lastPathComponent ?? "", characterCount: 0, date: now)
            fullText = nil
        } else if let string = pasteboard.string(forType: .string), !string.isEmpty {
            item = ClipboardPrivacy.classify(string, hideSecrets: hideSecrets, previewLength: previewLength, now: now)
            if case .secret = item.kind { fullText = nil } else { fullText = string }
        } else if types.contains(NSPasteboard.PasteboardType.tiff.rawValue) || types.contains(NSPasteboard.PasteboardType.png.rawValue) {
            item = ClipboardItem(kind: .image, preview: "Image", characterCount: 0, date: now)
            fullText = nil
        } else {
            return
        }
        latest = item
        expiryToken?.cancel()
        expiryToken = MainScheduler.shared.schedule(after: 60) { [weak self] in self?.fullText = nil }
        onCopy?(item)
    }

    // MARK: - Quick actions (all user-initiated)

    var canOpen: Bool { latest?.kind == .url && fullText != nil }
    var canMakePlain: Bool { latest?.kind == .text && fullText != nil }

    func openLink() {
        guard canOpen, let text = fullText?.trimmingCharacters(in: .whitespacesAndNewlines), let url = URL(string: text) else { return }
        NSWorkspace.shared.open(url)
    }

    /// Replaces rich text on the clipboard with plain text.
    func makePlainText() {
        guard let text = fullText else { return }
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    func clearPasteboard() {
        pasteboard.clearContents()
        lastChangeCount = pasteboard.changeCount
        clear()
    }
}
